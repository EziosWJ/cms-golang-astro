import { createRequire } from 'node:module';
import { readFile, writeFile, mkdir } from 'node:fs/promises';
const ready = process.env.CMS_GIT_BROWSER_READY;
if (!ready || !process.env.CMS_PLAYWRIGHT_MODULE || !process.env.CMS_CHROMIUM_PATH) throw Error('Use opt-in Git browser harness and installed Playwright/Chromium paths');
const require = createRequire(process.env.CMS_PLAYWRIGHT_MODULE);
if (require('./package.json').version !== '1.63.0') throw Error('Playwright 1.63.0 required');
const { chromium } = require('playwright');
const browser = await chromium.launch({ executablePath: process.env.CMS_CHROMIUM_PATH, headless: true, args: ['--no-sandbox'] });
if (browser.version() !== '153.0.8010.12') throw Error('Chromium 153.0.8010.12 required');
const base = (await readFile(ready, 'utf8')).trim();
const page = await browser.newPage();
const errors = []; page.on('pageerror', (e) => errors.push(e.message));
const evidence = [];
try {
  await page.goto(base + '/login');
  await page.locator('#username').fill('admin'); await page.locator('#password').fill('admin123');
  await page.getByRole('button', { name: '登录', exact: true }).click(); await page.waitForURL('**/content/articles');
  await page.goto(base + '/settings/git');
  await page.locator('#git-token').fill('test-browser-token');
  await page.getByRole('button', { name: '检测连接并读取仓库', exact: true }).click();
  await page.getByText('已连接 author，发现 1 个可选公开仓库。', { exact: true }).waitFor();
  await page.locator('#git-repo').selectOption('author/inputs');
  await page.locator('#git-source').fill('source/cms');
  await page.getByRole('button', { name: '读取目标分支', exact: true }).click();
  await page.getByText('仓库为空，将创建填写的默认分支。', { exact: true }).waitFor();
  await page.getByRole('button', { name: '保存连接', exact: true }).click();
  await page.getByText('连接已保存，Token 不会回显。', { exact: true }).waitFor();
  if (await page.locator('#git-token').inputValue()) throw Error('Token remains after save');
  const storage = await page.evaluate(() => JSON.stringify({ local: { ...localStorage }, session: { ...sessionStorage } }));
  if (storage.includes('test-browser-token')) throw Error('Token in browser storage');
  evidence.push('connection, repository discovery, empty branch, encrypted save and no token persistence');
  await page.reload(); await page.getByText('已保存 author 的连接。', { exact: true }).waitFor();
  if (await page.locator('#git-token').inputValue()) throw Error('Token returned after reload');
  await page.goto(base + '/content/publications');
  await page.getByRole('button', { name: '推送当前已发布站点', exact: true }).click();
  await page.getByText('已推送', { exact: true }).first().waitFor({ timeout: 30000 });
  await page.getByRole('button', { name: '推送当前已发布站点', exact: true }).click();
  await page.getByText('已推送（输入未变化）', { exact: true }).waitFor({ timeout: 30000 });
  await page.getByRole('button', { name: '详情', exact: true }).first().click();
  await page.getByRole('link', { name: '查看或重新运行 Actions', exact: true }).waitFor();
  evidence.push('manual first push, polling, no-op, task detail and commit/Actions links');
  await page.setViewportSize({ width: 390, height: 844 });
  await page.goto(base + '/settings/git'); await page.locator('#git-source').waitFor();
  if (await page.evaluate(() => document.documentElement.scrollWidth > innerWidth)) throw Error('Mobile connection overflow');
  await mkdir('.runtime/git-spec-publication', { recursive: true });
  await page.screenshot({ path: '.runtime/git-spec-publication/git-mobile.png', fullPage: true });
  evidence.push('390px connection form');
  if (errors.length) throw Error(errors.join('\n'));
  await writeFile('.runtime/git-spec-publication/browser-result.json', JSON.stringify({ evidence, errors, playwright: '1.63.0', chromium: browser.version() }, null, 2));
  console.log(JSON.stringify(evidence));
} finally {
  await browser.close(); await writeFile(ready + '.done', 'done');
}
