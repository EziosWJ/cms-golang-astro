-- +goose Up
-- 站点配置从单行单例变为多行集合（ADR-0009 决策一）。
--
-- local 站点 id 固定为 1：cms_media_ref 中 owner_type='config' 的既有引用
-- owner_id 就是 1（见 internal/siteconfig/siteconfig.go 的 SetReferences 调用），
-- 保持 1 可让既有引用与计数零改动，迁移里无需任何回填 UPDATE。
--
-- 新列的 DEFAULT 直接取 local 的取值，服务于两件事：
--   1. 既有单行库升级时，ADD COLUMN ... DEFAULT 正好把那一行回填成 local；
--   2. 空库的 seed/00007_site_config.sql 无需修改（它只写
--      id/version/data/saved_at/saved_by，新列走 DEFAULT 即正确的 local 行）。
-- 应用在新增非 local 站点时必须显式传入 site_key 与 role；若 role 被遗漏，
-- 第二次插入会被「恰有一条 local」的部分唯一索引拒绝——这是 fail-safe，
-- 不是宽容的默认值。DEFAULT 只服务于回填与种子，不服务于新站点。
--
-- 站点名不新增列：继续使用 data JSON 中的 SiteName（可修改），与不可变的
-- site_key（产物目录名与交付记录键）分离，避免出现第二份真相。

-- 内联列级 CHECK(id=1) 在 PostgreSQL 中的默认约束名是 cms_site_config_id_check。
-- 删掉它，表才能接受多行。
ALTER TABLE cms_site_config DROP CONSTRAINT cms_site_config_id_check;
-- 保留既有显式 id=1，同时让新行自动分配（与 cms_config_revision 的既有做法一致）。
ALTER TABLE cms_site_config ALTER COLUMN id ADD GENERATED BY DEFAULT AS IDENTITY (START WITH 2);

ALTER TABLE cms_site_config ADD COLUMN site_key VARCHAR(64) NOT NULL DEFAULT 'local';
ALTER TABLE cms_site_config ADD CONSTRAINT uk_cms_site_config_site_key UNIQUE (site_key);

ALTER TABLE cms_site_config ADD COLUMN role VARCHAR(16) NOT NULL DEFAULT 'local';
ALTER TABLE cms_site_config ADD CONSTRAINT ck_cms_site_config_role CHECK (role IN ('local','remote'));

ALTER TABLE cms_site_config ADD COLUMN status INTEGER NOT NULL DEFAULT 1;
ALTER TABLE cms_site_config ADD CONSTRAINT ck_cms_site_config_status CHECK (status IN (0,1));
-- 仓库惯例 1=启用 0=停用；local 不可停用。
ALTER TABLE cms_site_config ADD CONSTRAINT ck_cms_site_config_local_active CHECK (role <> 'local' OR status = 1);

-- 「恰有一条 local」：role='local' 的行最多一条；role='remote' 可有多条。
CREATE UNIQUE INDEX uk_cms_site_config_local_role ON cms_site_config (role) WHERE role = 'local';

-- local 行不可删除；非 local 行可删（是否已被交付记录引用由应用层判断）。
-- +goose StatementBegin
CREATE FUNCTION cms_reject_local_site_delete() RETURNS trigger AS $$ BEGIN IF OLD.role = 'local' THEN RAISE EXCEPTION 'the local site config cannot be deleted'; END IF; RETURN OLD; END; $$ LANGUAGE plpgsql;
-- +goose StatementEnd
CREATE TRIGGER cms_site_config_local_no_delete BEFORE DELETE ON cms_site_config FOR EACH ROW EXECUTE FUNCTION cms_reject_local_site_delete();

-- site_key 与 role 写入后不可变。
--   site_key 是产物目录名与交付记录键（ADR-0009 决策一），改动它会让历史产物与
--   未来的交付记录指向错误目录；role 决定「哪一份是本地链路使用的那份」，
--   允许改 role 会让「恰有一条 local」静默失效（零条 local 也能通过约束）。
-- WHEN 子句精确限定：只有这两列被改动时才拒绝，正常的保存路径
-- （version / saved_at / saved_by / data 的更新）必须继续成功。
-- +goose StatementBegin
CREATE FUNCTION cms_reject_site_identity_mutation() RETURNS trigger AS $$ BEGIN RAISE EXCEPTION 'the site key and role are immutable'; END; $$ LANGUAGE plpgsql;
-- +goose StatementEnd
CREATE TRIGGER cms_site_config_identity_immutable BEFORE UPDATE ON cms_site_config FOR EACH ROW WHEN (OLD.site_key IS DISTINCT FROM NEW.site_key OR OLD.role IS DISTINCT FROM NEW.role) EXECUTE FUNCTION cms_reject_site_identity_mutation();

-- 配置修订按站点归属回填。
-- 只对 cms_config_revision 加列：不重建该表、不改 version 的全局唯一约束、
-- 不动 cms_config_revision_immutable 触发器与 cms_reject_config_mutation 函数。
-- ADD COLUMN 是 DDL，不触发行触发器；且 DEFAULT 由 PostgreSQL 直接写入既有行，
-- 因此这里既不需要也不可能使用 UPDATE（会被不可变触发器 ABORT）。
ALTER TABLE cms_config_revision ADD COLUMN site_id BIGINT NOT NULL DEFAULT 1;

-- +goose Down
-- 回滚顺序（重要）：先执行本 schema Down，再回滚 seed 流。
-- goose 默认先回滚 seed，而已应用的 seed/00007_site_config.sql 的 Down 是
-- `DELETE FROM cms_site_config WHERE id=1;`，在本迁移已应用时会被
-- cms_site_config_local_no_delete 触发器拒绝（已实测，错误为
-- 'the local site config cannot be deleted'）。该触发器的存在是票面要求
-- （local 不可删由数据库保证），既有 seed 迁移不得修改，因此正确的回滚顺序是
-- schema 先降到 00014，再回滚 seed。
ALTER TABLE cms_config_revision DROP COLUMN site_id;

DROP TRIGGER cms_site_config_identity_immutable ON cms_site_config;
DROP FUNCTION cms_reject_site_identity_mutation();

DROP TRIGGER cms_site_config_local_no_delete ON cms_site_config;
DROP FUNCTION cms_reject_local_site_delete();

DROP INDEX uk_cms_site_config_local_role;

ALTER TABLE cms_site_config DROP CONSTRAINT ck_cms_site_config_local_active;
ALTER TABLE cms_site_config DROP CONSTRAINT ck_cms_site_config_status;
ALTER TABLE cms_site_config DROP CONSTRAINT ck_cms_site_config_role;
ALTER TABLE cms_site_config DROP CONSTRAINT uk_cms_site_config_site_key;
ALTER TABLE cms_site_config DROP COLUMN status;
ALTER TABLE cms_site_config DROP COLUMN role;
ALTER TABLE cms_site_config DROP COLUMN site_key;

ALTER TABLE cms_site_config ALTER COLUMN id DROP IDENTITY IF EXISTS;
-- 还原 00011 的单行单例约束。若集合中仍有非 local 行，本句会失败；
-- 这是回滚的已知前提：Down 只对「只剩 local 一行」的库可用。
ALTER TABLE cms_site_config ADD CONSTRAINT cms_site_config_id_check CHECK (id = 1);
